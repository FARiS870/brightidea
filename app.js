
const form = document.querySelector("#idea-form");
const topicInput = document.querySelector("#topic");
const formatInput = document.querySelector("#format");
const languageInput = document.querySelector("#language");
const audienceInput = document.querySelector("#audience");
const emptyState = document.querySelector("#empty-state");
const result = document.querySelector("#result");
const copyButton = document.querySelector("#copy-btn");

let latestPlan = "";

form.addEventListener("submit", async (event) => {
  event.preventDefault();

  const topic = topicInput.value.trim();

  if (!topic) {
    topicInput.focus();
    return;
  }

  const submitButton = form.querySelector(
    'button[type="submit"]'
  );

  const originalButtonText = submitButton?.textContent;

  if (submitButton) {
    submitButton.disabled = true;
    submitButton.textContent = "Generating...";
  }

  copyButton.disabled = true;

  try {
    const response = await fetch(
      "https://brightidea-api.onrender.com/api/generate",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          topic,
          format: formatInput.value,
          language: languageInput.value,
          audience: audienceInput.value
        })
      }
    );

    const data = await response.json();

    if (!response.ok) {
      throw new Error(
        data.error || "Could not generate content."
      );
    }

    latestPlan = data.result;

    const lines = latestPlan
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean);

    document.querySelector("#out-title").textContent =
      lines[0] || "Your AI-generated content";

    document.querySelector("#out-hook").textContent =
      latestPlan;

    document.querySelector("#out-hook").style.whiteSpace =
      "pre-wrap";

    document.querySelector("#out-next").textContent =
      "Generated by BrightIdea AI.";

    const outline = document.querySelector("#out-outline");
    outline.replaceChildren();

    emptyState.classList.add("hidden");
    result.classList.remove("hidden");
    copyButton.disabled = false;
  } catch (error) {
    alert(
      error.message ||
      "Connection failed. Please try again."
    );
  } finally {
    if (submitButton) {
      submitButton.disabled = false;
      submitButton.textContent = originalButtonText;
    }
  }
});

copyButton.addEventListener("click", async () => {
  if (!latestPlan) return;

  try {
    await navigator.clipboard.writeText(latestPlan);
    copyButton.textContent = "Copied!";
  } catch {
    const temp = document.createElement("textarea");
    temp.value = latestPlan;
    document.body.appendChild(temp);
    temp.select();
    document.execCommand("copy");
    temp.remove();
    copyButton.textContent = "Copied!";
  }

  setTimeout(() => {
    copyButton.textContent = "Copy plan";
  }, 1400);
});
